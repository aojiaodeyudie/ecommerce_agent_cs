def get_shop_profile(shop_id: str | None) -> dict | None:
    """返回商家身份配置；智能客服（ai/None）返回 None。"""
    if not shop_id or shop_id == "ai":
        return None
    return SHOP_PROFILES.get(shop_id)


def build_shop_system_prompt(base_prompt: str, shop_id: str | None) -> str:
    """把商家身份注入到基础系统提示词之前，返回完整系统提示词（#G2）。"""
    profile = get_shop_profile(shop_id)
    if profile is None:
        return base_prompt
    return (
        f"{profile['tone']}\n"
        f"【本店经营范围】{profile['scope']}\n"
        f"【服务准则】{profile['tips']}\n\n"
        f"（以下为通用客服行为规范，需与本店身份结合执行）\n"
        f"{base_prompt}"
    )
